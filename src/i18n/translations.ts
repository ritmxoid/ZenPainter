const SUPPORTED_LIST: SupportedLanguage[] = [
  'en',
  'ru',
  'uk',
  'be',
  'kk',
  'es',
  'pt',
  'fr',
  'de',
  'it',
  'pl',
  'nl',
  'tr',
  'ar',
  'hi',
  'zh',
  'ja',
  'ko',
  'vi',
  'id',
  'th',
];

export function detectBrowserLanguage(): SupportedLanguage {
  if (typeof navigator === 'undefined') return 'en';
  const candidates =
    Array.isArray(navigator.languages) && navigator.languages.length > 0
      ? navigator.languages
      : [navigator.language];

  for (const raw of candidates) {
    if (!raw) continue;
    const base = raw.toLowerCase().split('-')[0] as SupportedLanguage;
    if (SUPPORTED_LIST.includes(base)) {
      return base;
    }
  }
  return 'en';
}

export function resolveLanguage(pref: LanguagePreference): SupportedLanguage {
  if (pref === 'auto') {
    return detectBrowserLanguage();
  }
  return SUPPORTED_LIST.includes(pref) ? pref : 'en';
}

export function getSavedLanguagePreference(): LanguagePreference {
  try {
    const saved = localStorage.getItem('bestpaint_lang');
    if (saved === 'auto' || SUPPORTED_LIST.includes(saved as SupportedLanguage)) {
      return saved as LanguagePreference;
    }
  } catch {
    // ignore storage access issues
  }
  return 'auto';
}

export function saveLanguagePreference(pref: LanguagePreference): void {
  try {
    localStorage.setItem('bestpaint_lang', pref);
  } catch {
    // ignore storage access issues
  }
}
